"""Run only the Agentic AI investigation stage on existing SOC artefacts.

Upstream detection, event generation, correlation, graph construction, and
risk assessment must already have produced the canonical output files. This
module deliberately does not rerun or mutate those stages.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import networkx as nx
import pandas as pd

from . import ollama_reasoner
from .soc_investigation import (
    AgenticInvestigationAgent,
    IncidentEvidenceTools,
    _write_report,
)


_REQUIRED_EVENT_COLUMNS = {
    "event_id",
    "start_time",
    "end_time",
    "src_ip",
    "dst_ip",
    "protocol",
    "flow_count",
}
_REQUIRED_INCIDENT_FIELDS = {
    "incident_id",
    "event_ids",
    "title",
    "start_time",
    "end_time",
    "triage",
    "graph_analysis",
}


def _read_inputs(output_dir: Path) -> tuple[dict[str, Any], pd.DataFrame, nx.DiGraph]:
    """Load and cross-check artefacts generated by the upstream SOC stages."""
    events_path = output_dir / "attack_events.csv"
    graph_path = output_dir / "attack_graph.gexf"
    incidents_path = output_dir / "incident_investigation.json"

    missing = [str(path.name) for path in (events_path, graph_path, incidents_path) if not path.is_file()]
    if missing:
        raise FileNotFoundError(
            "AI-only investigation requires existing upstream artefacts in the same "
            f"output directory. Missing: {', '.join(missing)}. "
            "Run the upstream detection/event/graph/risk stages first."
        )

    try:
        payload = json.loads(incidents_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"Could not read valid incident JSON from {incidents_path}: {exc}") from exc
    if not isinstance(payload, dict) or not isinstance(payload.get("incidents"), list):
        raise ValueError(
            "incident_investigation.json must be an object containing an 'incidents' array."
        )

    events = pd.read_csv(events_path, low_memory=False, encoding="latin1")
    missing_columns = sorted(_REQUIRED_EVENT_COLUMNS - set(events.columns))
    if missing_columns:
        raise ValueError(
            f"attack_events.csv is missing required columns: {missing_columns}"
        )
    if events["event_id"].isna().any():
        raise ValueError("attack_events.csv contains null event IDs.")
    events["event_id"] = events["event_id"].astype(str).str.strip()
    if events["event_id"].eq("").any() or events["event_id"].duplicated().any():
        raise ValueError("attack_events.csv requires non-empty, unique event IDs.")

    for column in ("start_time", "end_time"):
        events[column] = pd.to_datetime(
            events[column], errors="coerce", utc=True, format="mixed"
        )
    if not events.empty and events[["start_time", "end_time"]].isna().any().any():
        raise ValueError("attack_events.csv contains invalid start_time/end_time values.")

    try:
        loaded_graph = nx.read_gexf(graph_path)
    except Exception as exc:
        raise ValueError(f"Could not load attack graph from {graph_path}: {exc}") from exc
    if not loaded_graph.is_directed():
        raise ValueError(
            "attack_graph.gexf must be a directed graph so incident/event edge "
            "direction is preserved."
        )
    graph = loaded_graph

    event_ids = set(events["event_id"])
    seen_incidents: set[str] = set()
    for index, incident in enumerate(payload["incidents"]):
        if not isinstance(incident, dict):
            raise ValueError(f"Incident at index {index} is not a JSON object.")
        missing_fields = sorted(_REQUIRED_INCIDENT_FIELDS - set(incident))
        if missing_fields:
            raise ValueError(
                f"Incident at index {index} is missing fields required by the AI "
                f"investigator: {missing_fields}."
            )
        incident_id = str(incident["incident_id"]).strip()
        if not incident_id or incident_id in seen_incidents:
            raise ValueError("Incident IDs must be non-empty and unique.")
        seen_incidents.add(incident_id)

        if not isinstance(incident["event_ids"], list) or not incident["event_ids"]:
            raise ValueError(f"{incident_id} must contain a non-empty event_ids array.")
        member_ids = [str(item) for item in incident["event_ids"]]
        if len(member_ids) != len(set(member_ids)):
            raise ValueError(f"{incident_id} contains duplicate event IDs.")
        unknown = sorted(set(member_ids) - event_ids)
        if unknown:
            raise ValueError(
                f"{incident_id} references events absent from attack_events.csv: {unknown[:10]}"
            )

        incident_node = f"incident:{incident_id}"
        if incident_node not in graph:
            raise ValueError(
                f"attack_graph.gexf does not contain {incident_node!r}; "
                "the upstream graph must include incident-to-event membership."
            )
        missing_nodes = [
            event_id for event_id in member_ids
            if f"event:{event_id}" not in graph
        ]
        if missing_nodes:
            raise ValueError(
                f"Graph nodes missing for {incident_id}: {missing_nodes[:10]}"
            )
        missing_memberships = [
            event_id for event_id in member_ids
            if not graph.has_edge(incident_node, f"event:{event_id}")
        ]
        if missing_memberships:
            raise ValueError(
                f"Graph is missing incident-to-event membership edges for "
                f"{incident_id}: {missing_memberships[:10]}"
            )

    return payload, events, graph


def _priority_key(incident: dict[str, Any]) -> tuple[float, str, str]:
    triage = incident.get("triage") or {}
    try:
        score = float(triage.get("priority_score", triage.get("risk_score", 0.0)))
    except (TypeError, ValueError):
        score = 0.0
    return (-score, str(incident.get("start_time", "")), str(incident.get("incident_id", "")))


def _update_recommendations(incident: dict[str, Any], investigation: dict[str, Any]) -> None:
    existing = incident.get("recommended_actions", [])
    if not isinstance(existing, list):
        existing = []
    additions = investigation.get("recommended_actions", [])
    if not isinstance(additions, list):
        additions = []
    incident["recommended_actions"] = existing + [
        item for item in additions if item not in existing
    ]


def _atomic_json_write(path: Path, value: dict[str, Any]) -> None:
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(
        json.dumps(value, indent=2, ensure_ascii=False, default=str) + "\n",
        encoding="utf-8",
    )
    temporary.replace(path)


def _stage_counts(incidents: list[dict[str, Any]]) -> dict[str, int]:
    agents = [
        item.get("investigation_agent", {})
        for item in incidents
        if isinstance(item.get("investigation_agent"), dict)
    ]
    return {
        "agent_tool_calls": sum(len(item.get("tool_calls", [])) for item in agents),
        "agent_reasoner_calls": sum(len(item.get("reasoner_calls", [])) for item in agents),
        "llm_tool_rounds": sum(int(item.get("llm_tool_rounds", 0) or 0) for item in agents),
        "llm_tool_calls_executed": sum(
            int(item.get("llm_tool_calls_executed", 0) or 0) for item in agents
        ),
        "reasoner_incidents": sum(
            item.get("mode") in {"tool_assisted_llm", "tool_assisted_llm_fallback"}
            for item in agents
        ),
        "agent_investigations_executed": sum(
            item.get("status") == "completed" for item in agents
        ),
        "agent_investigations_skipped": sum(
            item.get("status") == "skipped_by_limit" for item in agents
        ),
    }


def run(
    output_dir: str | Path,
    *,
    reasoner=None,
    max_incidents: int | None = 1,
) -> dict[str, Any]:
    """Run AI investigation only; preserve every upstream detection artefact."""
    if max_incidents is not None and (
        isinstance(max_incidents, bool)
        or not isinstance(max_incidents, int)
        or max_incidents < 1
    ):
        raise ValueError("max_incidents must be a positive integer or None for all incidents.")

    out = Path(output_dir)
    if not out.exists() or not out.is_dir():
        raise NotADirectoryError(f"Output directory does not exist: {out}")

    payload, events, graph = _read_inputs(out)
    incidents = payload["incidents"]
    tools = IncidentEvidenceTools(incidents, events, graph)
    agent = AgenticInvestigationAgent(tools, reasoner=reasoner)

    ordered = sorted(incidents, key=_priority_key)
    selected = ordered if max_incidents is None else ordered[:max_incidents]
    selected_ids = {str(item["incident_id"]) for item in selected}
    processed: list[dict[str, Any]] = []

    for incident in ordered:
        incident_id = str(incident["incident_id"])
        if incident_id not in selected_ids:
            # Preserve any pre-existing deterministic/LLM investigation. If
            # upstream has not created one, mark the skipped state explicitly.
            if not isinstance(incident.get("investigation_agent"), dict):
                incident["investigation_agent"] = {
                    "agent": "AgenticInvestigationAgent",
                    "mode": "not_run_limit",
                    "status": "skipped_by_limit",
                    "reasoner_error": None,
                    "reasoner_calls": [],
                    "llm_tool_rounds": 0,
                    "llm_tool_requests": 0,
                    "llm_tool_calls_executed": 0,
                    "plan": [],
                    "tool_calls": [],
                    "findings": [],
                    "model_findings_accepted": 0,
                    "model_findings_rejected": 0,
                    "attack_hypotheses": incident.get("attack_hypotheses", []),
                    "recommended_actions": [],
                    "narrative": (
                        "AI investigation was not run because the configured "
                        "max_incidents limit was reached. Upstream incident and "
                        "risk-assessment evidence were preserved."
                    ),
                }
            continue

        investigation = agent.investigate(incident_id)
        incident["investigation_agent"] = investigation
        _update_recommendations(incident, investigation)
        processed.append({
            "incident_id": incident_id,
            "status": investigation.get("status"),
            "mode": investigation.get("mode"),
            "reasoner_error": investigation.get("reasoner_error"),
        })

    # Keep the original incident ordering in the canonical JSON/report.
    _atomic_json_write(out / "incident_investigation.json", payload)
    _write_report(
        incidents,
        events,
        graph,
        out / "incident_investigation_report.md",
    )

    counts = _stage_counts(incidents)
    summary = {
        "stage": "agentic_ai_investigation_only",
        "upstream_stages_reexecuted": False,
        "reasoner_enabled": reasoner is not None,
        "reasoner_model": (
            ollama_reasoner._model_name() if reasoner is ollama_reasoner.reasoner else None
        ),
        "configured_incident_limit": max_incidents,
        "processed_incident_count": len(processed),
        "processed_incidents": processed,
        **counts,
        "outputs": [
            "incident_investigation.json",
            "incident_investigation_report.md",
            "soc_pipeline_manifest.json",
            "agentic_investigation_summary.json",
        ],
    }
    _atomic_json_write(out / "agentic_investigation_summary.json", summary)

    manifest_path = out / "soc_pipeline_manifest.json"
    if manifest_path.is_file():
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise ValueError(f"Invalid SOC pipeline manifest at {manifest_path}: {exc}") from exc
        if not isinstance(manifest, dict):
            raise ValueError("soc_pipeline_manifest.json must contain a JSON object.")
        manifest_counts = manifest.setdefault("counts", {})
        if not isinstance(manifest_counts, dict):
            manifest_counts = {}
            manifest["counts"] = manifest_counts
        manifest_counts.update(counts)
        artifacts = manifest.setdefault("artifacts", [])
        if isinstance(artifacts, list) and "agentic_investigation_summary.json" not in artifacts:
            artifacts.append("agentic_investigation_summary.json")
        manifest["agentic_investigation_stage"] = {
            "entry_point": "python -m attack_graph.agentic_investigator",
            "upstream_stages_reexecuted": False,
            "reasoner_enabled": reasoner is not None,
            "processed_incident_count": len(processed),
            "processed_incidents": processed,
        }
        for stage in manifest.get("stages", []):
            if isinstance(stage, dict) and stage.get("name") == "agentic_investigation":
                stage.update({
                    "status": "completed",
                    "tool_calls": counts["agent_tool_calls"],
                    "reasoner_calls": counts["agent_reasoner_calls"],
                    "llm_tool_rounds": counts["llm_tool_rounds"],
                    "reasoner_incidents": counts["reasoner_incidents"],
                    "agent_investigations_executed": counts["agent_investigations_executed"],
                    "agent_investigations_skipped": counts["agent_investigations_skipped"],
                })
        _atomic_json_write(manifest_path, manifest)

    pipeline_summary_path = out / "pipeline_summary.json"
    if pipeline_summary_path.is_file():
        try:
            pipeline_summary = json.loads(pipeline_summary_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise ValueError(f"Invalid pipeline summary at {pipeline_summary_path}: {exc}") from exc
        if not isinstance(pipeline_summary, dict):
            raise ValueError("pipeline_summary.json must contain a JSON object.")
        soc_summary = pipeline_summary.setdefault("soc_investigation", {})
        if isinstance(soc_summary, dict):
            soc_summary.update(counts)
        _atomic_json_write(pipeline_summary_path, pipeline_summary)

    return summary


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Run only the Agentic AI investigation stage on existing SOC incidents. "
            "Detection, event generation, graph construction and risk assessment are not rerun."
        )
    )
    parser.add_argument(
        "output_dir",
        type=Path,
        help="Existing pipeline output directory containing attack_events.csv, attack_graph.gexf and incident_investigation.json.",
    )
    parser.add_argument(
        "--max-incidents",
        type=int,
        default=1,
        help="Maximum number of highest-priority incidents to investigate (default: 1).",
    )
    parser.add_argument(
        "--all-incidents",
        action="store_true",
        help="Investigate every candidate incident; may trigger many local Ollama calls.",
    )
    parser.add_argument(
        "--deterministic",
        action="store_true",
        help="Do not call Ollama; run the deterministic evidence/tool baseline only.",
    )
    parser.add_argument(
        "--model",
        default=None,
        help="Ollama model name (defaults to OLLAMA_MODEL or qwen2.5:7b-instruct).",
    )
    args = parser.parse_args(argv)

    try:
        reasoner = None
        limit = None if args.all_incidents else args.max_incidents
        if limit is not None and limit < 1:
            raise ValueError("--max-incidents must be at least 1.")

        if not args.deterministic:
            if args.model:
                import os
                os.environ["OLLAMA_MODEL"] = args.model
            ready = ollama_reasoner.check_ollama()
            print(
                f"Ollama ready: {ready['host']} | model: {ready['model']}. "
                "Running AI investigation only."
            )
            reasoner = ollama_reasoner.reasoner
        else:
            print("Deterministic mode selected; no LLM call will be made.")

        result = run(
            args.output_dir,
            reasoner=reasoner,
            max_incidents=limit,
        )
    except Exception as exc:
        print(f"Agentic AI investigation failed: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1

    print("\nAGENTIC AI INVESTIGATION COMPLETE")
    print("=" * 48)
    print(f"Incidents processed : {result['processed_incident_count']}")
    print(f"Reasoner enabled    : {result['reasoner_enabled']}")
    print(f"Reasoner calls      : {result['agent_reasoner_calls']}")
    print(f"LLM tool calls      : {result['llm_tool_calls_executed']}")
    print(f"JSON dossier        : {args.output_dir / 'incident_investigation.json'}")
    print(f"Markdown report     : {args.output_dir / 'incident_investigation_report.md'}")
    print(f"Stage summary       : {args.output_dir / 'agentic_investigation_summary.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
